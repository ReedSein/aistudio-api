#!/usr/bin/env bash
# Environment setup for aistudio-api.
# Detects host platform and configures project-level dependencies.
#
# On Termux:
#   - Ensures essential Termux packages (uv, ca-certificates, curl, proot-distro).
#   - Uses the repository's TUR index and committed dependency lock.
#   - Links system ruff into .venv/bin/ruff if available.
#
# On Desktop / Docker / Linux / macOS / Windows:
#   - Leaves configuration pristine to fetch official PyPI wheels directly.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PROJECT_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"

log() { printf '[setup-env] %s\n' "$*" >&2; }

is_termux() {
    [[ -n "${PREFIX:-}" && "${PREFIX}" == *"/com.termux"* ]] || command -v pkg >/dev/null 2>&1
}

if is_termux; then
    log "Termux environment detected."

    # Install runtime packages; developer tooling is optional.
    NEEDED_PKGS=()
    # CFFI and PyYAML still need small native builds on a clean Termux install.
    for p in python git ca-certificates curl proot-distro uv gum clang pkg-config; do
        if ! command -v "${p}" >/dev/null 2>&1 && ! dpkg -s "${p}" >/dev/null 2>&1; then
            NEEDED_PKGS+=("${p}")
        fi
    done

    if [[ ${#NEEDED_PKGS[@]} -gt 0 ]]; then
        log "Installing missing Termux packages: ${NEEDED_PKGS[*]}"
        pkg update -y
        pkg install -y "${NEEDED_PKGS[@]}"
    fi

    # Retire only the exact configuration generated by the original installer.
    # uv.toml takes precedence over the repository's pyproject.toml settings.
    UV_CONFIG="${PROJECT_ROOT}/uv.toml"
    OLD_CONFIG=$(cat <<'EOF'
# Auto-generated by scripts/setup-env.sh for Termux
# Directs uv to resolve prebuilt Android wheels from TUR without compilation.
[[index]]
name = "tur"
url = "https://termux-user-repository.github.io/pypi/"
extra = true
EOF
)
    if [[ -L "${UV_CONFIG}" ]]; then
        log "uv.toml is a symbolic link; move it aside to use the fork's dependency settings."
        exit 1
    elif [[ -f "${UV_CONFIG}" ]]; then
        if [[ "$(cat "${UV_CONFIG}")" == "${OLD_CONFIG}" ]]; then
            rm -- "${UV_CONFIG}"
            log "Removed the obsolete generated uv.toml; using repository settings."
        else
            log "Custom uv.toml shadows repository settings; move it aside before continuing."
            exit 1
        fi
    fi
    if ! proot-distro list --quiet >/dev/null; then
        log "Repairing the proot-distro runtime package..."
        pkg reinstall -y proot-distro
        proot-distro --version >/dev/null
    fi

    # 3. Optional: link precompiled ruff into .venv if available
    if command -v ruff >/dev/null 2>&1 && [[ -d "${PROJECT_ROOT}/.venv/bin" && ! -e "${PROJECT_ROOT}/.venv/bin/ruff" ]]; then
        ln -sf "$(command -v ruff)" "${PROJECT_ROOT}/.venv/bin/ruff"
        log "Linked system ruff into .venv/bin/ruff."
    fi

    log "Termux environment ready. Run 'uv sync --locked' to install tested dependencies."
else
    log "Standard Linux/Desktop/Docker environment detected. No extra platform configuration needed."
fi

"""Optional cleanup of an original-author installation left on Termux."""

from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

from termux_diagnostics import get_store, install_script_logging
from termux_runtime import LEGACY_PROOT_NAME, Installation, ManagerError, operation_lock

AUTHOR_ORIGINS = (
    "https://github.com/DeconstructedCube/aistudio-api",
    "git@github.com:DeconstructedCube/aistudio-api",
)
CONFIRM_WORD = "CLEAN"
GENERATED_UV_TOML = """# Auto-generated by scripts/setup-env.sh for Termux
# Directs uv to resolve prebuilt Android wheels from TUR without compilation.
[[index]]
name = "tur"
url = "https://termux-user-repository.github.io/pypi/"
extra = true
"""
DATA_NAMES = ("data", "dumps", "server-logs", ".env", "chromium-profile")
KEEP_TRACKED_NAMES = ("config.yaml", ".env")
PROGRAM_DIR_NAMES = (".venv", ".cloakbrowser", ".git")


def _load_registered() -> Installation | None:
    try:
        return Installation.load()
    except (ManagerError, OSError):
        return None


def _run_git(root: Path, *args: str) -> subprocess.CompletedProcess[str]:
    result = subprocess.run(
        ["git", "-C", str(root), *args],
        text=True,
        capture_output=True,
        timeout=60,
        check=False,
    )
    get_store().emit(
        "legacy_git_operation", operation=args[0], returncode=result.returncode
    )
    if result.returncode:
        get_store().text("legacy_git_error", result.stderr)
    return result


def _is_author_origin(url: str) -> bool:
    return url.strip().removesuffix(".git") in AUTHOR_ORIGINS


def _decode_args(entry: Path) -> list[str]:
    try:
        raw = (entry / "cmdline").read_bytes()
    except OSError:
        return []
    return raw.decode("utf-8", "replace").rstrip("\0").split("\0")


def _service_pids(root: Path) -> list[int]:
    resolved = root.resolve()
    pids: list[int] = []
    for entry in Path("/proc").iterdir():
        if not entry.name.isdigit() or int(entry.name) == os.getpid():
            continue
        args = _decode_args(entry)
        if "main.py" not in args:
            continue
        matched = str(resolved) in args
        if not matched:
            try:
                matched = (entry / "cwd").resolve() == resolved
            except OSError:
                matched = False
        if matched:
            pids.append(int(entry.name))
    return pids


def _pids_using_container(name: str) -> list[int]:
    pattern = re.compile(rf"/installed-rootfs/{re.escape(name)}(?:/|$)")
    pids: list[int] = []
    for entry in Path("/proc").iterdir():
        if not entry.name.isdigit() or int(entry.name) == os.getpid():
            continue
        if any(pattern.search(arg) for arg in _decode_args(entry)):
            pids.append(int(entry.name))
    return pids


def _installed_containers() -> list[str] | None:
    if shutil.which("proot-distro") is None:
        return None
    result = subprocess.run(
        ["proot-distro", "list", "--quiet"],
        text=True,
        capture_output=True,
        timeout=30,
        check=False,
    )
    if result.returncode:
        get_store().text(
            "legacy_container_probe_error", result.stderr, returncode=result.returncode
        )
        return None
    return [line.strip() for line in result.stdout.splitlines() if line.strip()]


def _remove_container(name: str) -> subprocess.CompletedProcess[str]:
    result = subprocess.run(
        ["proot-distro", "remove", name],
        text=True,
        capture_output=True,
        timeout=300,
        check=False,
    )
    get_store().text(
        "legacy_container_output",
        result.stdout,
        channel="stdout",
        returncode=result.returncode,
    )
    get_store().text(
        "legacy_container_output",
        result.stderr,
        channel="stderr",
        returncode=result.returncode,
    )
    return result


def _parent_chain_has_symlink(root: Path, path: Path) -> bool:
    current = path.parent
    while current != root:
        if current.is_symlink():
            return True
        if current == current.parent:
            return True
        current = current.parent
    return False


@dataclass
class ContainerPlan:
    name: str | None = None
    action: str = "absent"
    reason: str = ""


@dataclass
class LegacySurvey:
    root: Path
    tracked_files: list[Path] = field(default_factory=list)
    keep_tracked: list[str] = field(default_factory=list)
    program_dirs: list[Path] = field(default_factory=list)
    generated_config: list[Path] = field(default_factory=list)
    kept_generated_config: list[Path] = field(default_factory=list)
    data_paths: list[Path] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)


def _survey(root: Path, *, clear_data: bool) -> LegacySurvey:
    survey = LegacySurvey(root)
    listing = _run_git(root, "ls-files", "-z")
    if listing.returncode:
        raise ManagerError(f"无法读取旧安装的文件清单：{listing.stderr.strip()}")
    for name in listing.stdout.split("\0"):
        if not name:
            continue
        relative = Path(name)
        if relative.is_absolute() or ".." in relative.parts:
            raise ManagerError("旧安装的文件路径超出目录范围，未执行任何删除。")
        if relative.name in KEEP_TRACKED_NAMES or relative.parts[0] in DATA_NAMES:
            survey.keep_tracked.append(name)
            continue
        survey.tracked_files.append(root / relative)
    for name in PROGRAM_DIR_NAMES:
        path = root / name
        if path.exists() or path.is_symlink():
            survey.program_dirs.append(path)
    uv_toml = root / "uv.toml"
    if uv_toml.is_file() and not uv_toml.is_symlink():
        if uv_toml.read_text(encoding="utf-8", errors="replace") == GENERATED_UV_TOML:
            survey.generated_config.append(uv_toml)
        else:
            survey.kept_generated_config.append(uv_toml)
    if clear_data:
        for name in (*DATA_NAMES, "config.yaml"):
            path = root / name
            if path.exists() or path.is_symlink():
                survey.data_paths.append(path)
    status = _run_git(root, "status", "--porcelain", "--untracked-files=no")
    if status.returncode == 0 and status.stdout.strip():
        count = len(status.stdout.strip().splitlines())
        survey.warnings.append(
            f"检测到 {count} 处未提交的本地代码改动，可能包含未备份的修改。"
        )
    local_only = _run_git(
        root,
        "rev-list",
        "--max-count=1",
        "--all",
        "HEAD",
        "--not",
        "--remotes",
        "--tags",
    )
    if local_only.returncode == 0 and local_only.stdout.strip():
        survey.warnings.append(
            "检测到仅保存在本地的提交或分支工作（未推送到任何远端）。"
        )
    return survey


def _plan_container(
    containers: list[str], registered_containers: tuple[str, ...]
) -> ContainerPlan:
    if LEGACY_PROOT_NAME not in containers:
        return ContainerPlan()
    plan = ContainerPlan(name=LEGACY_PROOT_NAME, action="delete")
    if LEGACY_PROOT_NAME in registered_containers:
        plan.action = "preserve"
        plan.reason = "当前安装仍在使用"
        return plan
    pids = _pids_using_container(LEGACY_PROOT_NAME)
    if pids:
        plan.action = "preserve"
        plan.reason = (
            "有进程正在使用（PID " + "、".join(str(pid) for pid in pids) + "）"
        )
    return plan


class LegacyCleanup:
    """Interactive removal of an original-author installation."""

    def __init__(self, *, clear_data: bool, repository_root: Path) -> None:
        self.clear_data = clear_data
        self.repository_root = repository_root.resolve()
        installation = _load_registered()
        self._registered_root = installation.root if installation is not None else None
        self._registered_containers = (
            (installation.proot_name,) if installation is not None else ()
        )

    def run(self) -> bool:
        get_store().emit("legacy_cleanup_start", clear_data=self.clear_data)
        root = self._select_root()
        if root is None:
            print("已取消清理。")
            return False
        survey: LegacySurvey | None = None
        if root.exists() or root.is_symlink():
            self._verify_target(root)
            pids = _service_pids(root)
            if pids:
                joined = "、".join(str(pid) for pid in pids)
                raise ManagerError(
                    f"旧安装可能仍在运行（PID {joined}）；"
                    "请先停止它再重新运行清理，未删除任何内容。"
                )
            survey = _survey(root.resolve(), clear_data=self.clear_data)
        else:
            print(f"原安装目录不存在：{root}")
        containers = _installed_containers()
        if containers is None:
            container = ContainerPlan()
            print("未检测到可用的 proot-distro，浏览器容器不在本次范围内。")
        else:
            container = _plan_container(containers, self._registered_containers)
        if survey is None and container.action == "absent":
            print("没有发现可清理的原版安装。")
            return False
        self._preview(survey, container)
        if (
            input(f"输入 {CONFIRM_WORD} 确认清理，其他输入取消：").strip()
            != CONFIRM_WORD
        ):
            get_store().emit("legacy_cleanup_cancelled")
            print("已取消清理。")
            return False
        return self._execute(survey, container)

    def _select_root(self) -> Path | None:
        guess = Path.home() / LEGACY_PROOT_NAME
        answer = input(
            f"请输入原作者安装的目录（回车使用 {guess}，输入 q 取消）："
        ).strip()
        if answer.lower() == "q":
            return None
        return Path(answer).expanduser() if answer else guess

    def _verify_target(self, root: Path) -> None:
        if root.is_symlink():
            raise ManagerError(
                f"目录是符号链接，为避免误删外部目标，未执行清理：{root}"
            )
        resolved = root.resolve()
        if resolved == self.repository_root:
            raise ManagerError("该目录是当前使用的工作区，不能作为原版安装清理。")
        if self._registered_root is not None and resolved == self._registered_root:
            raise ManagerError("该目录是已登记的本项目安装，不能作为原版安装清理。")
        if not (resolved / ".git").exists():
            raise ManagerError(f"目录不是 Git 检出，无法确认为原作者安装：{resolved}")
        origin = _run_git(resolved, "remote", "get-url", "origin")
        if origin.returncode or not _is_author_origin(origin.stdout.strip()):
            raise ManagerError(
                f"目录来源不是原作者仓库（origin 不符），未删除任何内容：{resolved}"
            )

    def _preview(self, survey: LegacySurvey | None, container: ContainerPlan) -> None:
        print("将清理原作者的旧安装：")
        if survey is not None:
            print("删除程序文件：")
            print(
                f"  {survey.root} 下 {len(survey.tracked_files)} 个 Git 跟踪的程序文件"
            )
            for path in survey.program_dirs:
                print(f"  {path}")
            for path in survey.generated_config:
                print(f"  {path}（自动生成的配置）")
        if container.action == "delete":
            print("删除浏览器容器：")
            print(f"  {container.name}")
        if survey is not None and self.clear_data and survey.data_paths:
            print("删除以下资料，删除后无法恢复：")
            for path in survey.data_paths:
                print(f"  {path}")
        print("保留：")
        if survey is not None and not self.clear_data:
            if survey.keep_tracked:
                print(f"  {'、'.join(survey.keep_tracked)}（用户配置）")
            kept_paths = [
                str(survey.root / name)
                for name in DATA_NAMES
                if (survey.root / name).exists()
            ]
            if kept_paths:
                print("  " + "、".join(kept_paths))
            for path in survey.kept_generated_config:
                print(f"  {path}（自定义配置）")
        print("  未接管的本地文件")
        print("  共享 Termux 工具、其他容器、共享镜像与全局缓存")
        print("  项目外的数据目录不会被触碰")
        if container.action == "preserve":
            print(f"  浏览器容器 {container.name}（{container.reason}）")
        if survey is not None:
            for warning in survey.warnings:
                print(f"警告：{warning}")

    def _execute(self, survey: LegacySurvey | None, container: ContainerPlan) -> bool:
        removed = 0
        pruned = 0
        failures: list[str] = []
        targets: list[Path] = []
        if survey is not None:
            targets = [
                *survey.tracked_files,
                *survey.program_dirs,
                *survey.generated_config,
                *survey.data_paths,
            ]
            for path in targets:
                if _parent_chain_has_symlink(survey.root, path):
                    failures.append(f"{path}（路径经过符号链接，未删除）")
                    continue
                try:
                    if path.is_symlink() or not path.is_dir():
                        path.unlink(missing_ok=True)
                    else:
                        shutil.rmtree(path)
                    removed += 1
                except OSError as exc:
                    failures.append(f"{path}（{exc.strerror or exc}）")
        if container.action == "delete" and container.name is not None:
            result = _remove_container(container.name)
            if result.returncode:
                failures.append(
                    f"浏览器容器 {container.name}（proot-distro remove 退出码 {result.returncode}）"
                )
            else:
                removed += 1
        if survey is not None and removed:
            pruned = self._prune_empty_dirs(survey.root, targets)
        if failures:
            get_store().emit(
                "legacy_cleanup_partial", removed=removed, failures=failures
            )
            print(f"清理部分完成：已删除 {removed} 项；以下 {len(failures)} 项未完成：")
            for item in failures:
                print(f"  {item}")
            return False
        summary = f"清理完成：共删除 {removed} 项"
        get_store().emit("legacy_cleanup_completed", removed=removed, pruned=pruned)
        if pruned:
            summary += f"，回收空目录 {pruned} 个"
        print(f"{summary}。")
        if survey is not None and not self.clear_data:
            print(f"原有配置与数据仍在：{survey.root}")
        return True

    @staticmethod
    def _prune_empty_dirs(root: Path, targets: list[Path]) -> int:
        """Remove only directories left empty by the cleanup, never the root."""
        pruned = 0
        candidates = {
            path.parent for path in targets if not _parent_chain_has_symlink(root, path)
        }
        for directory in sorted(
            candidates, key=lambda item: len(item.parts), reverse=True
        ):
            current = directory
            while current != root and current != current.parent:
                try:
                    current.rmdir()
                except OSError:
                    break
                pruned += 1
                current = current.parent
        return pruned


def interactive_cleanup(*, clear_data: bool, repository_root: Path) -> bool:
    """Menu entry; the caller already holds the operation lock."""
    return LegacyCleanup(clear_data=clear_data, repository_root=repository_root).run()


def main() -> int:
    install_script_logging("legacy-cleanup")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--clear-data",
        action="store_true",
        help="同时删除旧安装的资料（不可恢复）",
    )
    args = parser.parse_args()
    repository_root = Path(__file__).resolve().parents[1]
    cleanup = LegacyCleanup(clear_data=args.clear_data, repository_root=repository_root)
    installation = _load_registered()
    try:
        if installation is not None:
            with operation_lock(installation):
                cleanup.run()
        else:
            cleanup.run()
    except (KeyboardInterrupt, EOFError):
        print("\n已取消清理。")
        return 0
    except (ManagerError, OSError) as exc:
        print(f"清理失败：{exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
